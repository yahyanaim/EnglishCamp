const escaped=(text:string)=>text.replace(/[.*+?^${}()|[\]\\]/g,"\\$&");
const byName=new Map(RESOURCE_LINKS.flatMap(resource=>resource.names.map(name=>[name.toLowerCase(),resource.url] as const)));
const pattern=new RegExp(`(?<![a-z0-9])(${Array.from(byName.keys()).sort((a,b)=>b.length-a.length).map(escaped).join('|')})(?![a-z0-9])`,'gi');
export function resourceParts(text:string){return text.split(pattern).filter(Boolean).map(value=>({text:value,url:byName.get(value.toLowerCase())}));}
